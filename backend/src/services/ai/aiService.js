const env = require('../../config/env');
const logger = require('../../utils/logger');
const mockAiProvider = require('./mockAiProvider');

/**
 * AI Service Gateway & Registry
 * Manages active AI provider, normalizes schema outputs, and provides fault tolerance.
 */
class AIService {
  constructor() {
    this.providerName = (env.AI_PROVIDER || 'mock').toLowerCase();
    this.provider = this.resolveProvider(this.providerName);
    logger.info(`[AIService] Initialized with active provider: "${this.providerName}"`);
  }

  /**
   * Resolve active AI provider instance
   */
  resolveProvider(name) {
    switch (name) {
      case 'mock':
        return mockAiProvider;
      case 'gemini':
      case 'groq':
        // Future phases: instantiate real providers if configured, fallback to mock if credentials missing
        logger.info(`[AIService] Provider "${name}" selected; running with Mock fallback for safe Phase 7 execution.`);
        return mockAiProvider;
      default:
        logger.warn(`[AIService] Unknown provider "${name}", defaulting to Mock.`);
        return mockAiProvider;
    }
  }

  /**
   * Analyze ticket content with normalization and bounds validation
   */
  async analyzeTicket(ticketData) {
    try {
      if (!ticketData || !ticketData.title) {
        throw new Error('Ticket title is required for AI analysis');
      }

      const rawResult = await this.provider.analyzeTicket(ticketData);

      // Validate & normalize against schema enum bounds
      const validCategories = ['billing', 'technical', 'account', 'feature_request', 'general'];
      const validPriorities = ['LOW', 'MEDIUM', 'HIGH', 'URGENT'];
      const validSentiments = ['POSITIVE', 'NEUTRAL', 'NEGATIVE', 'FRUSTRATED'];

      const normalized = {
        suggestedCategory: validCategories.includes(rawResult.suggestedCategory)
          ? rawResult.suggestedCategory
          : 'general',
        suggestedPriority: validPriorities.includes(rawResult.suggestedPriority)
          ? rawResult.suggestedPriority
          : 'MEDIUM',
        sentiment: validSentiments.includes(rawResult.sentiment)
          ? rawResult.sentiment
          : 'NEUTRAL',
        intent: String(rawResult.intent || 'GENERAL_SUPPORT').substring(0, 100),
        summary: String(rawResult.summary || `Summary for ${ticketData.title}`).substring(0, 500),
        tags: Array.isArray(rawResult.tags)
          ? rawResult.tags.map((t) => String(t).trim().toLowerCase()).filter(Boolean)
          : [],
        confidence: typeof rawResult.confidence === 'number' ? rawResult.confidence : 0.9,
        provider: this.providerName,
        isSimulated: this.providerName === 'mock',
        analyzedAt: new Date(),
      };

      return normalized;
    } catch (error) {
      logger.error(`[AIService] Analysis error: ${error.message}`);
      // Return safe fallback so system continues functioning
      return {
        suggestedCategory: ticketData.category || 'general',
        suggestedPriority: ticketData.priority || 'MEDIUM',
        sentiment: 'NEUTRAL',
        intent: 'GENERAL_SUPPORT',
        summary: `Support ticket regarding: "${ticketData.title}". (AI analysis fallback).`,
        tags: ['support'],
        confidence: 0.5,
        provider: this.providerName,
        isSimulated: true,
        fallback: true,
        error: error.message,
        analyzedAt: new Date(),
      };
    }
  }

  /**
   * Generate suggested reply with fault tolerance
   */
  async generateSuggestedReply(context) {
    try {
      if (!context || !context.ticket) {
        throw new Error('Ticket context is required for reply suggestion');
      }

      const rawResult = await this.provider.generateSuggestedReply(context);

      return {
        suggestedReply: String(rawResult.suggestedReply || '').trim(),
        rationale: String(rawResult.rationale || 'Context-aware customer response generated by AI assistant.'),
        confidence: typeof rawResult.confidence === 'number' ? rawResult.confidence : 0.9,
        provider: this.providerName,
        isSimulated: this.providerName === 'mock',
        generatedAt: new Date(),
      };
    } catch (error) {
      logger.error(`[AIService] Reply generation error: ${error.message}`);
      const customerName = context.ticket?.customer?.name || 'Customer';
      return {
        suggestedReply: `Hello ${customerName},\n\nThank you for reaching out. We have received your ticket regarding "${context.ticket?.title}" and our support staff is actively reviewing the details.\n\nBest regards,\nSupport Operations`,
        rationale: 'Standard operational acknowledgment fallback.',
        confidence: 0.5,
        provider: this.providerName,
        isSimulated: true,
        fallback: true,
        error: error.message,
        generatedAt: new Date(),
      };
    }
  }

  /**
   * Grounded Question-Answering using Knowledge Base chunks (RAG)
   */
  async answerKnowledgeQuery({ query = '', retrievedChunks = [] }) {
    try {
      const rawResult = await this.provider.answerKnowledgeQuery({
        query: String(query).trim(),
        retrievedChunks: Array.isArray(retrievedChunks) ? retrievedChunks : [],
      });

      return {
        answer: String(rawResult.answer || '').trim(),
        confidence: typeof rawResult.confidence === 'number' ? rawResult.confidence : 0.9,
        hasSufficientContext: Boolean(rawResult.hasSufficientContext),
        sources: Array.isArray(rawResult.sources) ? rawResult.sources : [],
        provider: this.providerName,
        isSimulated: this.providerName === 'mock',
        answeredAt: new Date(),
      };
    } catch (error) {
      logger.error(`[AIService] Knowledge Q&A error: ${error.message}`);
      return {
        answer:
          "The Knowledge Assistant is currently experiencing a technical interruption. " +
          "Please consult the published documentation directly or submit a support ticket.",
        confidence: 0.1,
        hasSufficientContext: false,
        sources: [],
        provider: this.providerName,
        isSimulated: true,
        fallback: true,
        error: error.message,
        answeredAt: new Date(),
      };
    }
  }
}

module.exports = new AIService();
