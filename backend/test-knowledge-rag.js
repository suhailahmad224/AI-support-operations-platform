const http = require('http');

function request(options, data) {
  return new Promise((resolve, reject) => {
    const req = http.request(options, (res) => {
      let body = '';
      res.on('data', (chunk) => (body += chunk));
      res.on('end', () => {
        try {
          resolve({ status: res.statusCode, data: JSON.parse(body) });
        } catch (e) {
          resolve({ status: res.statusCode, raw: body });
        }
      });
    });
    req.on('error', reject);
    if (data) req.write(JSON.stringify(data));
    req.end();
  });
}

async function login(email, password) {
  const res = await request(
    {
      hostname: 'localhost',
      port: 5000,
      path: '/api/auth/login',
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
    },
    { email, password }
  );
  return { token: res.data?.data?.token, user: res.data?.data?.user };
}

async function runTestSuite() {
  console.log('--- STARTING KNOWLEDGE BASE + RAG VERIFICATION SUITE --- \n');
  let passed = 0;
  let failed = 0;

  function assert(condition, message, details = '') {
    if (condition) {
      console.log(`[PASS] ${message}`);
      passed++;
    } else {
      console.error(`[FAIL] ${message} ${details}`);
      failed++;
    }
  }

  try {
    const admin = await login('admin@platform.com', 'AdminPass123!');
    const agent = await login('agent@platform.com', 'AgentPass123!');
    const customer = await login('customer@platform.com', 'CustomerPass123!');

    const adminToken = admin.token;
    const agentToken = agent.token;
    const customerToken = customer.token;

    const testSlug = `setup-two-factor-auth-${Date.now()}`;
    const draftSlug = `internal-security-policy-${Date.now()}`;

    // 1. Admin creates a published article with multi-paragraph content
    const articlePayload = {
      title: 'How to Setup Two-Factor Authentication (2FA)',
      slug: testSlug,
      category: 'security',
      tags: ['2fa', 'authentication', 'security', 'authenticator'],
      isPublished: true,
      content: 
        'Two-factor authentication adds an essential layer of security to your company account.\n\n' +
        'To enable 2FA, navigate to your Profile Settings and locate the Security Preferences tab. ' +
        'Select Enable 2FA, which will generate a unique QR code on your screen.\n\n' +
        'Open your preferred authenticator app, such as Google Authenticator, 1Password, or Authy. ' +
        'Scan the QR code and enter the 6-digit confirmation code generated by your app.\n\n' +
        'Be sure to store your emergency backup codes in a safe offline location. Backup codes can ' +
        'be used if your physical mobile device is lost, stolen, or replaced.',
    };

    const createRes = await request(
      {
        hostname: 'localhost',
        port: 5000,
        path: '/api/articles',
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${adminToken}`,
        },
      },
      articlePayload
    );

    assert(createRes.status === 201 && createRes.data?.success === true, '1. Admin creates published 2FA article (201)');

    // 2. Verify auto-chunking generated multiple chunks
    const createdArticle = createRes.data?.data;
    assert(
      Array.isArray(createdArticle?.chunks) && createdArticle.chunks.length >= 2,
      `2. Content pre-chunker generated ${createdArticle?.chunks?.length} chunks with preserved boundaries`
    );

    // 3. Reject duplicate slug creation
    const dupRes = await request(
      {
        hostname: 'localhost',
        port: 5000,
        path: '/api/articles',
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${adminToken}`,
        },
      },
      articlePayload
    );
    assert(dupRes.status === 409, '3. Duplicate slug creation rejected with 409 Conflict');

    // 4. Role-Based Access Control: Customer and Agent blocked from creating articles
    const custCreateRes = await request(
      {
        hostname: 'localhost',
        port: 5000,
        path: '/api/articles',
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${customerToken}`,
        },
      },
      {
        title: 'Hacked Article',
        content: 'This should not be allowed.',
      }
    );
    assert(custCreateRes.status === 403, '4a. Customer strictly forbidden from creating articles (403)');

    const agentCreateRes = await request(
      {
        hostname: 'localhost',
        port: 5000,
        path: '/api/articles',
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${agentToken}`,
        },
      },
      {
        title: 'Agent Article',
        content: 'Agents should not publish articles directly.',
      }
    );
    assert(agentCreateRes.status === 403, '4b. Agent strictly forbidden from creating articles (403)');

    // 5. Admin creates an UNPUBLISHED draft article
    const draftPayload = {
      title: 'Internal Operational Playbook For Tier-3 Incidents',
      slug: draftSlug,
      category: 'troubleshooting',
      tags: ['internal', 'incident', 'tier3'],
      isPublished: false,
      content: 'This internal document contains confidential instructions for high-severity database failovers.',
    };

    const draftCreateRes = await request(
      {
        hostname: 'localhost',
        port: 5000,
        path: '/api/articles',
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${adminToken}`,
        },
      },
      draftPayload
    );
    assert(draftCreateRes.status === 201, '5. Admin creates unpublished draft article (201)');

    // 6. Customer lists articles: sees published article, does NOT see unpublished draft
    const custListRes = await request({
      hostname: 'localhost',
      port: 5000,
      path: '/api/articles',
      method: 'GET',
      headers: { Authorization: `Bearer ${customerToken}` },
    });
    const customerArticleSlugs = (custListRes.data?.data || []).map((a) => a.slug);
    assert(
      customerArticleSlugs.includes(testSlug) && !customerArticleSlugs.includes(draftSlug),
      '6. Customer article list isolates published articles and completely hides unpublished drafts'
    );

    // 7. Customer tries to access unpublished draft directly: 404
    const custDirectRes = await request({
      hostname: 'localhost',
      port: 5000,
      path: `/api/articles/${draftSlug}`,
      method: 'GET',
      headers: { Authorization: `Bearer ${customerToken}` },
    });
    assert(custDirectRes.status === 404, '7. Customer direct access to unpublished draft blocked with 404 Not Found');

    // 8. Admin accesses unpublished draft directly: 200 OK
    const adminDirectRes = await request({
      hostname: 'localhost',
      port: 5000,
      path: `/api/articles/${draftSlug}`,
      method: 'GET',
      headers: { Authorization: `Bearer ${adminToken}` },
    });
    assert(adminDirectRes.status === 200, '8. Admin permitted to view unpublished draft article (200)');

    // 9. RAG Lexical Chunk Search: query for 2FA keywords
    const ragSearchRes = await request(
      {
        hostname: 'localhost',
        port: 5000,
        path: '/api/articles/rag/search',
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${customerToken}`,
        },
      },
      {
        query: 'how to scan authenticator QR code for 2fa',
        topK: 3,
      }
    );
    const topChunk = ragSearchRes.data?.data?.chunks?.[0];
    assert(
      ragSearchRes.status === 200 &&
        ragSearchRes.data?.data?.count > 0 &&
        (topChunk?.articleSlug === testSlug || topChunk?.articleSlug === 'configuring-two-factor-authentication') &&
        topChunk?.matchedTokens?.includes('authenticator'),
      '9. Lexical BM25 retrieval ranked relevant 2FA chunk first with keyword matches'
    );

    // 10. RAG search verifies customer cannot retrieve chunks from unpublished draft
    const draftSearchRes = await request(
      {
        hostname: 'localhost',
        port: 5000,
        path: '/api/articles/rag/search',
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${customerToken}`,
        },
      },
      {
        query: 'confidential high-severity database failovers playbook',
        topK: 3,
      }
    );
    const retrievedDraftChunks = (draftSearchRes.data?.data?.chunks || []).filter((c) => c.articleSlug === draftSlug);
    assert(
      retrievedDraftChunks.length === 0,
      '10. RAG chunk retrieval strictly filters out unpublished draft content for ordinary customers'
    );

    // 11. RAG Knowledge Assistant Q&A: relevant question generates grounded answer
    const askRes = await request(
      {
        hostname: 'localhost',
        port: 5000,
        path: '/api/articles/rag/ask',
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${customerToken}`,
        },
      },
      {
        query: 'What should I do with my backup codes when setting up 2FA?',
      }
    );
    assert(
      askRes.status === 200 &&
        askRes.data?.data?.hasSufficientContext === true &&
        askRes.data?.data?.sources?.length > 0 &&
        askRes.data?.data?.answer?.includes('Two-Factor Authentication'),
      '11. Knowledge Assistant generated grounded response with source citations'
    );

    // 12. RAG Knowledge Assistant Q&A: irrelevant query returns no-relevant-source fallback
    const irrevRes = await request(
      {
        hostname: 'localhost',
        port: 5000,
        path: '/api/articles/rag/ask',
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${customerToken}`,
        },
      },
      {
        query: 'How do quantum gravitational singularities affect warp drives?',
      }
    );
    assert(
      irrevRes.status === 200 &&
        irrevRes.data?.data?.hasSufficientContext === false &&
        irrevRes.data?.data?.sources?.length === 0 &&
        irrevRes.data?.data?.answer?.includes("couldn't find any relevant information"),
      '12. Irrelevant query returns honest no-source fallback without fabricating answers'
    );

    // 13. Input validation: short title/content rejected
    const badInputRes = await request(
      {
        hostname: 'localhost',
        port: 5000,
        path: '/api/articles',
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${adminToken}`,
        },
      },
      {
        title: 'Hi',
        content: 'Short',
      }
    );
    assert(badInputRes.status === 400, '13. Input validator rejects undersized article title/content (400)');

    // 14. Admin toggles publish status
    const toggleRes = await request({
      hostname: 'localhost',
      port: 5000,
      path: `/api/articles/${draftSlug}/publish`,
      method: 'PATCH',
      headers: { Authorization: `Bearer ${adminToken}` },
    });
    assert(
      toggleRes.status === 200 && toggleRes.data?.data?.isPublished === true,
      '14. Admin successfully published previously unpublished draft article'
    );

    // 15. Admin deletes test articles
    const del1 = await request({
      hostname: 'localhost',
      port: 5000,
      path: `/api/articles/${testSlug}`,
      method: 'DELETE',
      headers: { Authorization: `Bearer ${adminToken}` },
    });
    const del2 = await request({
      hostname: 'localhost',
      port: 5000,
      path: `/api/articles/${draftSlug}`,
      method: 'DELETE',
      headers: { Authorization: `Bearer ${adminToken}` },
    });
    assert(del1.status === 200 && del2.status === 200, '15. Admin cleaned up test articles (200 OK)');

  } catch (error) {
    console.error('Fatal error during test suite:', error);
    failed++;
  }

  console.log(`\n--- TEST SUMMARY: ${passed} PASSED, ${failed} FAILED ---`);
  if (failed > 0) {
    process.exit(1);
  }
}

runTestSuite();
